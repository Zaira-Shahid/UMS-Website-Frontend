// Generates components/ui/lucide.tsx: the lucide icons this site uses, as plain components with no client-side code.
// lucide-react's own icons are client components, so each one on a page is re-rendered in the browser during hydration.
// Drawing them as plain SVG on the server gives identical markup with no hydration cost. Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = ["components", "app", "lib", "content"].flatMap((d) => walk(join(root, d))).filter((f) => /\.tsx?$/.test(f) && !f.split("\\").join("/").endsWith("components/ui/lucide.tsx"));
const names = new Set();
for (const f of files) {
  const s = readFileSync(f, "utf8");
  for (const m of s.matchAll(/import\s*\{([^}]*)\}\s*from\s*"lucide-react"/g)) {
    for (const n of m[1].split(",")) { const t = n.trim().replace(/^type\s+/, ""); if (t && t !== "LucideIcon") names.add(t); }
  }
}
const barrel = readFileSync(join(root, "node_modules/lucide-react/dist/esm/lucide-react.mjs"), "utf8");
const fileFor = {};
for (const m of barrel.matchAll(/export \{([^}]*)\} from '\.\/icons\/([^']+)\.mjs'/g)) {
  for (const part of m[1].split(",")) { const n = part.trim().split(" as ").pop(); fileFor[n] = m[2]; }
}
const byFile = new Map();
for (const n of [...names].sort()) {
  const ic = fileFor[n]; if (!ic) throw new Error("no icon file for " + n);
  if (!byFile.has(ic)) byFile.set(ic, []);
  byFile.get(ic).push(n);
}
let out = `// GENERATED by scripts/gen-icons.mjs from lucide-react (ISC licence). Do not edit by hand.
import { createElement, type ReactNode, type SVGProps } from "react";

export type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & { size?: number | string };
export type LucideIcon = (props: IconProps) => ReactNode;

type Node = [string, Record<string, string>][];

function make(name: string, node: Node): LucideIcon {
  const Icon = ({ size, width, height, strokeWidth, className, children, ...rest }: IconProps) => {
    const labelled = Boolean(children) || Object.entries(rest).some(([k, v]) => (k.startsWith("aria-") || k === "role" || k === "title") && v != null);
    return createElement(
      "svg",
      {
        xmlns: "http://www.w3.org/2000/svg",
        width: width ?? size ?? 24,
        height: height ?? size ?? 24,
        viewBox: "0 0 24 24",
        fill: "none",
        stroke: "currentColor",
        strokeWidth: strokeWidth ?? 2,
        strokeLinecap: "round",
        strokeLinejoin: "round",
        className: ["lucide", "lucide-" + name, className].filter(Boolean).join(" "),
        ...(labelled ? {} : { "aria-hidden": "true" }),
        ...rest,
      },
      ...node.map(([tag, attrs]) => createElement(tag, attrs)),
      children,
    );
  };
  return Icon;
}
`;
for (const [ic, list] of byFile) {
  const src = readFileSync(join(root, "node_modules/lucide-react/dist/esm/icons", ic + ".mjs"), "utf8");
  const m = src.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!m) throw new Error("no data in " + ic);
  const data = new Function("return " + m[1])();
  const node = JSON.stringify(data.node);
  const first = list[0];
  out += `const ${first} = make(${JSON.stringify(data.name)}, ${node});\n`;
  for (const n of list.slice(1)) out += `const ${n} = ${first};\n`;
}
out += `\nexport { ${[...names].filter((n) => n !== "LucideIcon").sort().join(", ")} };\n`;
writeFileSync(join(root, "components/ui/lucide.tsx"), out);
console.log("icons:", names.size, "files:", byFile.size);
